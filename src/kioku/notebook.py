"""An optional notebook: a folder of notes the agent writes, one per idea.

The notebook is the learner's reference while they answer: a formula, a
signature, an example. It uses the format of a vault (`notes/<id>.md` with YAML
frontmatter, the title as the first alias, `[[id|label]]` links), so the same
tools read both. A note is named by its idea's id, which never changes; its
links are the idea's edges. An index note per area lists the notes in it.

kioku writes a note's skeleton and the index notes. The body of a note is the
agent's. Notes are never evidence.
"""

from __future__ import annotations

from pathlib import Path

from .model import Model
from .records import Idea

MARK = "<!-- below: the formula or signature, one example, a figure where it helps -->"
GENERATED = "<!-- generated by `kioku note`; edits are overwritten -->"


class Notebook:
    def __init__(self, root: Path):
        self.root = root

    @property
    def notes(self) -> Path:
        return self.root / "notes"

    def path(self, idea: Idea) -> Path:
        return self.notes / f"{idea.id}.md"

    def has(self, idea: Idea) -> bool:
        return self.path(idea).exists()

    def ensure(self, m: Model, idea: Idea) -> tuple[Path, bool]:
        """The idea's note, written as a skeleton when it does not exist yet:
        (its path, whether it was just made)."""
        p = self.path(idea)
        if p.exists():
            return p, False
        self.notes.mkdir(parents=True, exist_ok=True)
        p.write_text(self.skeleton(m, idea))
        return p, True

    def skeleton(self, m: Model, idea: Idea) -> str:
        out = ["---", f'aliases: ["{idea.name}"]', "type: note", f"kind: {idea.kind}",
               f"area: {idea.area}", "---", "", f"# {idea.name}", "", idea.statement, "",
               MARK, ""]
        for label, edges in (("Needs", m.needs), ("Uses", m.uses)):
            names = [f"[[{j}|{m.name(j)}]]" for j in edges.get(idea.id, ())]
            if names:
                out.append(f"{label}: {', '.join(names)}")
        out.append(f"Area: [[{_index_id(idea.area)}|{idea.area}]]")
        return "\n".join(out) + "\n"

    def write_indexes(self, m: Model) -> int:
        """One index note per area that holds a note, and one for the whole notebook."""
        self.notes.mkdir(parents=True, exist_ok=True)
        noted = {i.id for i in m.ideas.values() if self.has(i)}
        areas = sorted(a for a in m.areas if any(i in noted for i in m.in_area(a, deep=True)))
        keep = {"index.md"}
        for area in areas:
            lines = ["---", f'aliases: ["{area}"]', "type: index", "---", "", GENERATED, "",
                     f"# {area}", ""]
            up = area.rsplit("/", 1)[0] if "/" in area else ""
            lines.append(f"Up: [[{_index_id(up)}|{up}]]" if up else "Up: [[index|notebook]]")
            subs = [s for s in m.children(area) if s in areas]
            if subs:
                lines += ["", "Areas:", *(f"- [[{_index_id(s)}|{s}]]" for s in subs)]
            own = [i for i in m.in_area(area) if i in noted]
            if own:
                lines += ["", "Notes:", *(f"- [[{i}|{m.name(i)}]] ({m.ideas[i].kind})"
                                          for i in own)]
            (self.notes / f"{_index_id(area)}.md").write_text("\n".join(lines) + "\n")
            keep.add(f"{_index_id(area)}.md")
        tops = [a for a in areas if "/" not in a]
        (self.notes / "index.md").write_text("\n".join(
            ["---", 'aliases: ["notebook"]', "type: index", "---", "", GENERATED, "",
             "# Notebook", "", *(f"- [[{_index_id(a)}|{a}]]" for a in tops)]) + "\n")
        for old in self.notes.glob("area--*.md"):  # an area that lost its last note
            if old.name not in keep:
                old.unlink()
        return len(areas)


def _index_id(area: str) -> str:
    return "area--" + area.replace("/", "--")
